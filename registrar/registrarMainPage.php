/* ── Handle release — system-generated e-certificate ────────────────
 * The certificate PDF is GENERATED by the system from the student's
 * record; the registrar only edits the content (title/body/officer/
 * date/remarks) in the release modal. The generated PDF is saved to
 * the record and emailed to the student as an attachment. */
if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($_POST['release_request'])) {
    if (!verifyCsrfToken()) {
        header("Location: registrarMainPage.php?view=main&error=csrf_fail");
        exit();
    }

    $req_id = (int)($_POST['req_id'] ?? 0);
    $row    = certificate_fetch($conn, $req_id);

    if (!$row) {
        header("Location: registrarMainPage.php?view=main&release_error=" . urlencode('Request not found.'));
        exit();
    }

    // ── State guard: only an ACTIVE request can be released ──────────
    // Already-Released rows must not be re-released (it would re-date the
    // request and orphan the previous PDF on disk); cancelled/rejected rows
    // must be re-queued to Pending first so the audit trail stays honest.
    if (in_array((string)$row['status'], ['Released', 'Cancelled'], true)) {
        $why = $row['status'] === 'Released'
            ? 'already released'
            : 'cancelled/rejected — re-queue it to Pending first';
        header("Location: registrarMainPage.php?view=main&release_error=" . urlencode("This request is {$why} and cannot be released."));
        exit();
    }

    // ── Registrar edits (fall back to system defaults when empty) ──
    $edits = [
        'title'         => db_utf8(trim((string)($_POST['cert_title']    ?? ''))),
        'body'          => db_utf8(trim((string)($_POST['cert_body']     ?? ''))),
        'officer_name'  => db_utf8(trim((string)($_POST['officer_name']  ?? ''))),
        'officer_title' => db_utf8(trim((string)($_POST['officer_title'] ?? ''))),
        'cert_date'     => trim((string)($_POST['cert_date']     ?? '')),
        'remarks'       => db_utf8(trim((string)($_POST['remarks']       ?? ''))),
    ];

    // Signing-officer default: the registrar currently logged in
    $q = $conn->prepare("SELECT first_name, last_name FROM users WHERE id = ?");
    $q->bind_param("i", $_SESSION['user_id']);
    $q->execute();
    $me = $q->get_result()->fetch_assoc();
    $q->close();
    $regNameDefault = $me ? trim($me['first_name'] . ' ' . $me['last_name']) : '';
    $certData = certificate_build_data($row, $edits, $regNameDefault);

    try {
        $pdf = generate_certificate_pdf($certData);
    } catch (Throwable $e) {
        error_log("Certificate generation failed (REQ-{$req_id}): " . $e->getMessage());
        header("Location: registrarMainPage.php?view=main&release_error=" . urlencode('Certificate generation failed. Please try again.'));
        exit();
    }

    // ── Save the generated PDF ──
    $uploads_fs  = dirname(__DIR__) . '/uploads';
    $dir         = $uploads_fs . '/e_certificates/';
    if (!is_dir($dir)) mkdir($dir, 0755, true);

    $filename = 'cert_' . $req_id . '_' . time() . '_' . rand(100, 999) . '.pdf';
    if (file_put_contents($dir . $filename, $pdf) === false) {
        header("Location: registrarMainPage.php?view=main&release_error=" . urlencode('Failed to save the certificate file. Please try again.'));
        exit();
    }

    // Replace: remove the previous certificate file if any
    if (!empty($row['e_certificate'])) {
        $old = $uploads_fs . '/' . ltrim($row['e_certificate'], '/');
        if (file_exists($old)) unlink($old);
    }

    $certWeb = 'uploads/e_certificates/' . $filename;

    $upd = $conn->prepare(
        "UPDATE document_requests
         SET status = 'Released', cancelled_by = NULL, rejection_reason = NULL,
             date_released = NOW(), e_certificate = ?
         WHERE id = ? AND status NOT IN ('Released','Cancelled')"
    );
    $upd->bind_param("si", $certWeb, $req_id);
    $upd->execute();
    $upd->close();

    // ── Email the certificate to the student ──
    $email = $fullName = null;
    $q = $conn->prepare("SELECT email, first_name, last_name FROM users WHERE id = ?");
    $q->bind_param("i", $row['student_pk']);
    $q->execute();
    $stu = $q->get_result()->fetch_assoc();
    $q->close();

    $mailSent = false;
    if ($stu && !empty($stu['email'])) {
        $fullName = trim($stu['first_name'] . ' ' . $stu['last_name']);
        $reqNo    = $certData['req_no'];
        $result   = send_certificate_email($stu['email'], $fullName, $reqNo, $row['document_type'], $certWeb);
        $mailSent = $result['ok'];
        if (!$mailSent) {
            error_log("Release mail failed for {$reqNo}: " . $result['error']);
        }
    } else {
        error_log("Release mail skipped (no email on file) for REQ-{$req_id}.");
    }

    // ── Audit: registrar released the document with a system e-cert ──
    // The wording reflects the REAL mail outcome — the audit must never
    // claim an email was sent when the delivery actually failed.
    audit_log($conn, 'CERTIFICATE_RELEASED', 'document_request', $certData['req_no'],
        "{$row['document_type']} — e-certificate generated"
        . (($stu && !empty($stu['email']))
            ? ($mailSent ? " and emailed to {$stu['email']}"
                         : " — email to {$stu['email']} FAILED (certificate is still downloadable from the dashboard)")
            : ' (no email on file — NOT emailed)'));

    header("Location: registrarMainPage.php?released=1&view=main");
    exit();
}

// ── Handle status update ───────────────────────────────────────────
if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($_POST['update_status'])) {
    // ── CSRF check ──
    if (!verifyCsrfToken()) {
        header("Location: registrarMainPage.php?view=main&error=csrf_fail");
        exit();
    }

    $req_id    = (int)($_POST['req_id'] ?? 0);
    $newStatus = $_POST['new_status'] ?? '';
    // Simplified flow: Pending → Processing → Released, plus Cancelled (reject).
    // ("Ready for Pickup" stays accepted so legacy rows can still be
    // re-saved without silently failing.)
    // 'Released' is deliberately NOT accepted here — releasing MUST go
    // through the e-certificate flow (release_request) so a student is
    // never told "released" while no certificate exists to download.
    $allowed   = ['Pending', 'Processing', 'Ready for Pickup', 'Cancelled'];

    if (in_array($newStatus, $allowed, true)) {
        $dbStatus    = $newStatus;
        $cancelledBy = null;

        // ── Audit: remember the current status for the change log ──
        $old = $conn->prepare("SELECT status FROM document_requests WHERE id = ?");
        $old->bind_param("i", $req_id);
        $old->execute();
        $oldStatus = (string)($old->get_result()->fetch_row()[0] ?? '?');
        $old->close();

        if ($newStatus === 'Cancelled') {
            // Registrar rejection — flagged so students cannot restore it.
            // A written reason is REQUIRED so the student knows why.
            $cancelledBy  = 'registrar';
            $rejectReason = db_utf8(trim((string)($_POST['reject_reason'] ?? '')));
            if ($rejectReason === '') {
                header("Location: registrarMainPage.php?error=reason_required");
                exit();
            }
        } else {
            $rejectReason = null;
        }

        $upd = $conn->prepare(
            "UPDATE document_requests
             SET status        = ?,
                 cancelled_by  = CASE
                                    WHEN ? = 'Cancelled' THEN ?
                                    WHEN ? IN ('Released','Pending') THEN NULL
                                    ELSE cancelled_by
                                 END,
                 rejection_reason = CASE
                                    WHEN ? = 'Cancelled' THEN ?
                                    ELSE NULL
                                 END,
                 date_released = CASE
                                    WHEN ? = 'Released' THEN NOW()
                                    WHEN ? = 'Pending'  THEN NULL
                                    ELSE date_released
                                 END
             WHERE id = ?"
        );
        $upd->bind_param("ssssssssi", $dbStatus, $dbStatus, $cancelledBy, $dbStatus, $dbStatus, $rejectReason, $dbStatus, $dbStatus, $req_id);
        $upd->execute();

        // ── Audit: registrar changed the request status ──
        if ($upd->affected_rows > 0) {
            audit_log($conn, 'STATUS_CHANGED', 'document_request',
                'REQ-' . str_pad((string) $req_id, 4, '0', STR_PAD_LEFT),
                "{$oldStatus} → {$dbStatus}"
                . ($cancelledBy !== null ? " (cancelled_by: {$cancelledBy})" : '')
                . (!empty($rejectReason) ? " — Reason: {$rejectReason}" : ''));
        }
        $upd->close();

        // 📧 Notify the student when the request reaches a key status
        notifyStudentStatus($conn, $req_id, $newStatus, $rejectReason ?? null, $cancelledBy);
    }
    // Stay in the requests table (not back to the dashboard) after acting
    header("Location: registrarMainPage.php?view=main");
    exit();
}

