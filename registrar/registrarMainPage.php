function countWhere($conn, $where, $types = '', $params = [])
{
    $n  = 0;
    $st = $conn->prepare("SELECT COUNT(*) FROM document_requests WHERE $where");
    if (!$st) return 0;
    if ($types) $st->bind_param($types, ...$params);
    $st->execute();
    $st->bind_result($n);
    $st->fetch();
    $st->close();
    return $n;
}

