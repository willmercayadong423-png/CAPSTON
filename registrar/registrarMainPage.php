/* ── Email the student when a request status changes ────────────────
 * Uses the shared mail API (phpLogics/mailer.php). Fires on
 * Processing (accepted), Released, and legacy "Ready for Pickup".
 * Failures are logged server-side and never block the update. */
function notifyStudentStatus(mysqli $conn, int $req_id, string $newStatus): void
{
    $notifyable = ['Processing', 'Ready for Pickup', 'Released'];
    if (!in_array($newStatus, $notifyable, true)) {
        return;
    }

    $q = $conn->prepare(
        "SELECT s.email, s.first_name, s.last_name, dr.document_type
         FROM document_requests dr
         JOIN students s ON dr.student_id = s.id
         WHERE dr.id = ?"
    );
    $q->bind_param("i", $req_id);
    $q->execute();
    $info = $q->get_result()->fetch_assoc();
    $q->close();

    if (!$info || empty($info['email'])) {
        return;
    }

    $fullName = trim(($info['first_name'] ?? '') . ' ' . ($info['last_name'] ?? ''));
    $reqNo    = 'REQ-' . str_pad((string) $req_id, 4, '0', STR_PAD_LEFT);

    $result = send_status_email(
        $info['email'],
        $fullName,
        $reqNo,
        $info['document_type'] ?? 'your document',
        $newStatus
    );

    if (!$result['ok']) {
        error_log("Status mail failed for {$reqNo} ({$newStatus}): " . $result['error']);
    }
}

/* ── Handle release — system-generated e-certificate ────────────────
 * The certificate PDF is GENERATED by the system from the student's
 * record; the registrar only edits the content (title/body/officer/
 * date/remarks) in the release modal. The generated PDF is saved to
 * the record and emailed to the student as an attachment. */
if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($_POST['release_request'])) {
    if (!verifyCsrfToken()) {
        header("Location: registrarMainPage.php?error=csrf_fail");
        exit();
    }

    $req_id = (int)$_POST['req_id'];
    $row    = certificate_fetch($conn, $req_id);

    if (!$row) {
        header("Location: registrarMainPage.php?release_error=" . urlencode('Request not found.'));
        exit();
    }

    // ── Registrar edits (fall back to system defaults when empty) ──
    $edits = [
        'title'         => trim((string)($_POST['cert_title']    ?? '')),
        'body'          => trim((string)($_POST['cert_body']     ?? '')),
        'officer_name'  => trim((string)($_POST['officer_name']  ?? '')),
        'officer_title' => trim((string)($_POST['officer_title'] ?? '')),
        'cert_date'     => trim((string)($_POST['cert_date']     ?? '')),
        'remarks'       => trim((string)($_POST['remarks']       ?? '')),
    ];

    // Signing-officer default: the registrar currently logged in
    $q = $conn->prepare("SELECT first_name, last_name FROM students WHERE id = ?");
    $q->bind_param("i", $_SESSION['user_id']);
    $q->execute();
    $me = $q->get_result()->fetch_assoc();
    $q->close();
    $regNameDefault = $me ? trim($me['first_name'] . ' ' . $me['last_name']) : '';
    $certData = certificate_build_data($row, $edits, $regNameDefault);

    try {
        $pdf = generate_certificate_pdf($certData);
    } catch (Throwable $e) {
        error_log("Certificate generation failed (REQ-{$req_id}): " . $e->getMessage());
        header("Location: registrarMainPage.php?release_error=" . urlencode('Certificate generation failed. Please try again.'));
        exit();
    }

    // ── Save the generated PDF ──
    $uploads_fs  = dirname(__DIR__) . '/uploads';
    $dir         = $uploads_fs . '/e_certificates/';
    if (!is_dir($dir)) mkdir($dir, 0755, true);

    $filename = 'cert_' . $req_id . '_' . time() . '_' . rand(100, 999) . '.pdf';
    if (file_put_contents($dir . $filename, $pdf) === false) {
        header("Location: registrarMainPage.php?release_error=" . urlencode('Failed to save the certificate file. Please try again.'));
        exit();
    }

    // Replace: remove the previous certificate file if any
    if (!empty($row['e_certificate'])) {
        $old = $uploads_fs . '/' . ltrim($row['e_certificate'], '/');
        if (file_exists($old)) unlink($old);
    }

    $certWeb = 'uploads/e_certificates/' . $filename;

    $upd = $conn->prepare(
        "UPDATE document_requests
         SET status = 'Released', cancelled_by = NULL,
             date_released = NOW(), e_certificate = ?
         WHERE id = ?"
    );
    $upd->bind_param("si", $certWeb, $req_id);
    $upd->execute();
    $upd->close();

    // ── Email the certificate to the student ──
    $email = $fullName = null;
    $q = $conn->prepare("SELECT email, first_name, last_name FROM students WHERE id = ?");
    $q->bind_param("i", $row['student_pk']);
    $q->execute();
    $stu = $q->get_result()->fetch_assoc();
    $q->close();

    if ($stu && !empty($stu['email'])) {
        $fullName = trim($stu['first_name'] . ' ' . $stu['last_name']);
        $reqNo    = $certData['req_no'];
        $result   = send_certificate_email($stu['email'], $fullName, $reqNo, $row['document_type'], $certWeb);
        if (!$result['ok']) {
            error_log("Release mail failed for {$reqNo}: " . $result['error']);
        }
    } else {
        error_log("Release mail skipped (no email on file) for REQ-{$req_id}.");
    }

    header("Location: registrarMainPage.php?released=1");
    exit();
}

// ── Handle status update ───────────────────────────────────────────
if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($_POST['update_status'])) {
    // ── CSRF check ──
    if (!verifyCsrfToken()) {
        header("Location: registrarMainPage.php?error=csrf_fail");
        exit();
    }

    $req_id    = (int)$_POST['req_id'];
    $newStatus = $_POST['new_status'];
    // Simplified flow: Pending → Processing → Released, plus Cancelled (reject).
    // Legacy values ("Ready for Pickup", "Unclaimed") stay accepted so old
    // rows can still be re-saved without silently failing.
    $allowed   = ['Pending', 'Processing', 'Ready for Pickup', 'Released', 'Unclaimed', 'Cancelled'];

    if (in_array($newStatus, $allowed, true)) {
        $dbStatus    = $newStatus;
        $cancelledBy = null;

        if ($newStatus === 'Unclaimed') {
            // Store as Cancelled with cancelled_by = 'unclaimed'
            $dbStatus    = 'Cancelled';
            $cancelledBy = 'unclaimed';
        } elseif ($newStatus === 'Cancelled') {
            // Registrar rejection — flagged so students cannot restore it
            $cancelledBy = 'registrar';
        }

        $upd = $conn->prepare(
            "UPDATE document_requests
             SET status        = ?,
                 cancelled_by  = CASE
                                    WHEN ? = 'Cancelled' THEN ?
                                    WHEN ? IN ('Released','Pending') THEN NULL
                                    ELSE cancelled_by
                                 END,
                 date_released = CASE
                                    WHEN ? = 'Released' THEN NOW()
                                    WHEN ? = 'Pending'  THEN NULL
                                    ELSE date_released
                                 END
             WHERE id = ?"
        );
        $upd->bind_param("ssssssi", $dbStatus, $dbStatus, $cancelledBy, $dbStatus, $dbStatus, $dbStatus, $req_id);
        $upd->execute();
        $upd->close();

        // 📧 Notify the student when the request reaches a key status
        notifyStudentStatus($conn, $req_id, $newStatus);
    }
    header("Location: registrarMainPage.php");
    exit();
}

